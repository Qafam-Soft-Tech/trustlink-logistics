/**
 * Receipt text for a completed delivery (share only — there is no receipt endpoint).
 * Pure TS, unit-tested.
 */
import type { Delivery, ProofOfDelivery } from './types';
import { formatDate, formatNaira } from '../formatters';
import { deliveryStatusLabel } from './tracking';

export function receiptText(delivery: Delivery, pod?: ProofOfDelivery | null): string {
  const lines = [
    'TrustLink Logistics — receipt',
    `Tracking: ${delivery.trackingNumber}`,
    `Status: ${deliveryStatusLabel(delivery.status)}`,
    `Route: ${delivery.pickupArea ?? '—'} → ${delivery.dropoffArea ?? '—'}`,
    `Package: ${delivery.packageType === 'document' ? 'Document' : 'Parcel'} · ${delivery.packageWeight} kg`,
    `Fare paid: ${formatNaira(delivery.fare ?? 0)}`,
    delivery.paymentReference ? `Payment ref: ${delivery.paymentReference}` : '',
    `Requested: ${formatDate(delivery.createdAt)}`,
    pod ? `Delivered to ${pod.recipientName} on ${formatDate(pod.createdAt)}` : '',
  ];
  return lines.filter(Boolean).join('\n');
}

/** `mailto:` URL that hands the receipt to the device's mail client (no server, no dependency). */
export function receiptMailto(delivery: Delivery, pod?: ProofOfDelivery | null, to?: string | null): string {
  const subject = `TrustLink receipt — ${delivery.trackingNumber}`;
  const params = `subject=${encodeURIComponent(subject)}&body=${encodeURIComponent(receiptText(delivery, pod))}`;
  return `mailto:${to ? encodeURIComponent(to) : ''}?${params}`;
}

export interface ReceiptColors {
  brand: string;
  text: string;
  muted: string;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Standalone HTML for the PDF receipt (rendered on device by `expo-print`).
 * Colours come from the theme so no literal brand values live in code.
 */
export function receiptHtml(delivery: Delivery, pod: Partial<ProofOfDelivery> | null | undefined, colors: ReceiptColors): string {
  const rows: Array<[string, string]> = [
    ['Tracking number', delivery.trackingNumber],
    ['Status', deliveryStatusLabel(delivery.status)],
    ['Route', `${delivery.pickupArea ?? '—'} → ${delivery.dropoffArea ?? '—'}`],
    ['Package', `${delivery.packageType === 'document' ? 'Document' : 'Parcel'} · ${delivery.packageWeight} kg`],
    ['Fare paid', formatNaira(delivery.fare ?? 0)],
  ];
  if (delivery.paymentReference) rows.push(['Payment ref', delivery.paymentReference]);
  rows.push(['Requested', formatDate(delivery.createdAt)]);
  if (pod) rows.push(['Delivered to', `${pod.recipientName ?? '—'} · ${formatDate(pod.createdAt)}`]);

  const photo = pod && pod.photoUrl && /^(https:|data:)/.test(pod.photoUrl)
    ? `<img src="${escapeHtml(pod.photoUrl)}" alt="Proof of delivery" style="width:100%;border-radius:8px;margin-top:16px" />`
    : '';

  return `<!doctype html><html><head><meta charset="utf-8" /><title>TrustLink receipt ${escapeHtml(delivery.trackingNumber)}</title></head>
<body style="font-family:-apple-system,Roboto,Arial,sans-serif;color:${escapeHtml(colors.text)};padding:32px">
  <h1 style="margin:0;font-size:22px;color:${escapeHtml(colors.brand)}">TrustLink Logistics</h1>
  <p style="margin:4px 0 24px;color:${escapeHtml(colors.muted)}">Secure. Swift. Strategic.</p>
  <h2 style="font-size:18px;margin:0 0 12px">Receipt</h2>
  <table style="width:100%;border-collapse:collapse">
    ${rows
      .map(
        ([label, value]) =>
          `<tr><td style="padding:8px 0;border-bottom:1px solid ${escapeHtml(colors.muted)}22;color:${escapeHtml(colors.muted)}">${escapeHtml(label)}</td><td style="padding:8px 0;border-bottom:1px solid ${escapeHtml(colors.muted)}22;text-align:right">${escapeHtml(value)}</td></tr>`,
      )
      .join('')}
  </table>
  ${photo}
  <p style="margin-top:32px;color:${escapeHtml(colors.muted)};font-size:12px">Generated by the TrustLink app.</p>
</body></html>`;
}
